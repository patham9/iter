import re, hashlib, subprocess, random
from pathlib import Path

DESCRIPTION = "Reasoning: transitive closure + symmetry + modus ponens over space.metta -> inferred.metta with NAL deduction (via metta/reasoning.metta)"
RUN_SH = Path.home() / 'PeTTa' / 'run.sh'
MAX_INFERRED = 1000

def _toks(s): return re.findall(r'\(|\)|[^\s()]+', s)
def _parse(t, i=0):
    if t[i] == '(':
        out = []; i += 1
        while t[i] != ')':
            x, i = _parse(t, i); out.append(x)
        return out, i + 1
    return t[i], i + 1
def _ser(x): return x if isinstance(x, str) else '(' + ' '.join(_ser(y) for y in x) + ')'

def transform(messages, all_context):
    runtime_dir = Path(__file__).parent.parent / 'metta'
    space_path = runtime_dir / 'space.metta'
    inferred_path = runtime_dir / 'inferred.metta'
    rfile = runtime_dir / 'reasoning.metta'
    if not space_path.exists() or not rfile.exists():
        return messages, all_context
    try:
        r = subprocess.run([str(RUN_SH), str(rfile)], cwd=str(runtime_dir),
                           capture_output=True, text=True, timeout=30)
        last = [l for l in r.stdout.strip().splitlines() if l.startswith('(')][-1]
        res, _ = _parse(_toks(last))
        inh = sorted((_ser(e[0]), _ser(e[1]), float(e[2]), float(e[3])) for e in res[0][1])
        rel = sorted((_ser(e[0]), _ser(e[1]), _ser(e[2]), float(e[3]), float(e[4])) for e in res[1])
    except Exception:
        return messages, all_context  # keep previous inferred.metta on any failure
    body = [f'((--> {a} {b}) (stv {f} {c}))' for a, b, f, c in inh]
    body += [f'((--> (× {a} {b}) {rl}) (stv {f} {c}))' for a, b, rl, f, c in rel]
    if len(body) > MAX_INFERRED:
        seed = int(hashlib.md5(space_path.read_text().encode()).hexdigest(), 16) % (2**32)
        idx = sorted(random.Random(seed).sample(range(len(body)), MAX_INFERRED))
        body = [body[i] for i in idx]
    head = [';; === Inferred facts (auto-generated by reasoning.metta via reasoning.py) ===',
            f';; Source: {space_path.name}', f';; Iterations: {res[0][0]}', '']
    inferred_path.write_text('\n'.join(head + body) + '\n')
    return messages, all_context
